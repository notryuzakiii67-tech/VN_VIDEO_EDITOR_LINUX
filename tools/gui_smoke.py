#!/usr/bin/env python3
"""Headless GUI smoke test for the editor.

Builds a small demo project (the "gameplay POV short" workflow), opens the real
``MainWindow`` on the offscreen Qt platform, drives it through the operations a
user would perform, and writes screenshots plus a pass/fail report.

Usage
-----
    python tools/gui_smoke.py [--out DIR] [--only name,name]

Environment
-----------
On a headless box without GL/X11 libraries, point ``LD_LIBRARY_PATH`` at the
stub libraries generated by ``tools/qt_offscreen_shim.py`` and set
``QT_QPA_PLATFORM=offscreen``.
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
import time
import traceback
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

RESULTS: list[tuple[str, bool, str]] = []


def check(name: str, fn) -> None:
    try:
        fn()
        RESULTS.append((name, True, ""))
        print(f"  [PASS] {name}", flush=True)
    except Exception as exc:                       # noqa: BLE001
        RESULTS.append((name, False, f"{type(exc).__name__}: {exc}"))
        print(f"  [FAIL] {name}: {type(exc).__name__}: {exc}", flush=True)
        traceback.print_exc(limit=6)


# --------------------------------------------------------------------------- #
#  Fixtures
# --------------------------------------------------------------------------- #

def make_media(tmp: Path) -> dict:
    """Generate the source clips the demo project needs (no network)."""
    from vn_editor.core import ffmpeg as ff

    out = {}
    game = tmp / "gameplay.mp4"
    if not game.exists():
        r = ff.ffmpeg(
            "-y", "-v", "error",
            "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=30:duration=8",
            "-f", "lavfi", "-i", "sine=frequency=330:duration=8",
            "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "128k", "-shortest", str(game), timeout=300)
        if not r.ok:
            raise RuntimeError(f"could not build test media: {r.stderr[-400:]}")
    out["gameplay"] = str(game)

    music = tmp / "music.wav"
    if not music.exists():
        # a click track at 2 Hz so beat detection has something real to find
        r = ff.ffmpeg("-y", "-v", "error", "-f", "lavfi",
                      "-i", "sine=frequency=1000:duration=8:sample_rate=48000",
                      "-af", "atempo=1.0,volume=0.5", "-c:a", "pcm_s16le",
                      str(music), timeout=120)
        if r.ok:
            out["music"] = str(music)
    return out


def build_project(media: dict):
    """The acceptance scenario: 16:9 gameplay -> 9:16, zoom, speed, captions."""
    from vn_editor.core import probe as probe_mod
    from vn_editor.core import project as pio
    from vn_editor.core import sfx as sfx_mod
    from vn_editor.core.ass import apply_text_animation
    from vn_editor.core.model import (Clip, MediaAsset, Project, TextProps,
                                      Transform)

    project = Project.create_default("Gameplay POV short", 1080, 1920, 30.0)
    src = media["gameplay"]
    info = probe_mod.probe(src, use_cache=False)
    asset = MediaAsset.from_info(info, src)
    project.assets.append(asset)

    track = project.ensure_track_for("video")
    clip = Clip(kind="video", track_id=track.id, start=0.0, duration=6.0)
    clip.path = src
    clip.asset_id = asset.id
    clip.name = "gameplay.mp4"
    clip.meta["has_audio"] = True
    # convert 16:9 -> 9:16: fill the frame then zoom slightly
    clip.transform = Transform(x=0.5, y=0.5, scale=1.12, fit="cover")
    clip.speed = 1.5
    project.add_clip(clip, track)

    caption_track = project.ensure_track_for("text")
    for text, start, anim in (("POV: YOU ARE HIM", 0.4, "pop_in"),
                              ("INSANE CLUTCH", 2.4, "zoom_in"),
                              ("GG EASY", 4.4, "fade_in")):
        t = Clip(kind="text", track_id=caption_track.id, start=start,
                 duration=1.6)
        t.text = TextProps(text=text, font="Bebas Neue", size=290.0,
                           color="#ffffff", outline_width=7.0,
                           outline_color="#000000", shadow=2.0)
        t.transform.y = 0.22
        apply_text_animation(t, anim, t.duration, 0.35)
        project.add_clip(t, caption_track)

    sticker_track = project.ensure_track_for("sticker")
    s = Clip(kind="sticker", track_id=sticker_track.id, start=3.0, duration=1.8)
    s.meta["sticker"] = "fire"
    s.meta["sticker_size"] = 0.18
    s.meta["sticker_anim"] = "pop_in"
    project.add_clip(s, sticker_track)

    sfx_track = project.ensure_track_for("audio")
    for key, at in (("fahhh", 2.2), ("thud", 3.9), ("get_out", 5.2)):
        path = sfx_mod.resolve(key)
        if not path:
            continue
        a = Clip(kind="audio", track_id=sfx_track.id, start=at, duration=1.2)
        a.path = path
        a.name = key
        a.meta["has_audio"] = True
        a.audio.volume = 0.9
        project.add_clip(a, sfx_track)

    project.beats = [0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0, 5.5]
    project.modifiers = 0
    return project


# --------------------------------------------------------------------------- #
#  Driver
# --------------------------------------------------------------------------- #

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="")
    ap.add_argument("--keep", action="store_true")
    args = ap.parse_args()

    out = Path(args.out) if args.out else Path(tempfile.mkdtemp(prefix="vngui-"))
    out.mkdir(parents=True, exist_ok=True)
    print(f"output dir: {out}")

    from PySide6.QtCore import Qt
    from PySide6.QtWidgets import QApplication
    app = QApplication.instance() or QApplication(sys.argv[:1])

    from vn_editor.ui import theme
    theme.register_bundled_fonts()
    app.setStyleSheet(theme.stylesheet())

    media = make_media(out)
    print("media:", media)

    from vn_editor.ui.main_window import MainWindow
    project = build_project(media)

    win = MainWindow(project)
    win.resize(1520, 950)
    win.show()

    def settle(ms: int = 220) -> None:
        end = time.time() + ms / 1000.0
        while time.time() < end:
            app.processEvents()
            time.sleep(0.01)

    settle(500)

    def shot(name: str):
        settle(250)
        path = out / f"{name}.png"
        ok = win.grab().save(str(path))
        assert ok, f"could not write {path}"
        return path

    print("\n== window ==")
    check("window builds and paints", lambda: shot("01_window"))

    print("\n== panels ==")
    check("media panel sees the import", lambda: (
        _assert(len(project.assets) >= 1, "no assets"),
        _assert(win.media.count_label.text().startswith("1"), 
                f"count label = {win.media.count_label.text()}")) and None)
    check("timeline shows 4 tracks", lambda: _assert(
        len(project.tracks) >= 4, f"{len(project.tracks)} tracks"))
    check("timeline draws clips", lambda: shot("02_timeline")) 

    print("\n== playback / scrubbing ==")

    def scrub():
        for t in (0.5, 1.5, 2.5, 3.5):
            win.seek(t)
            settle(420)
        win.seek(1.0)
        settle(600)
        img = win.preview.widget._image
        _assert(img is not None and not img.isNull(),
                "preview never produced a frame")
    check("preview renders frames while scrubbing", scrub)
    check("preview screenshot", lambda: shot("03_preview"))

    def frame_step():
        t0 = win.ctx.playhead()
        win.step_frame(1)
        settle(320)
        t1 = win.ctx.playhead()
        _assert(abs(t1 - t0 - 1 / 30) < 1e-6, f"{t0} -> {t1}")
    check("frame stepping", frame_step)

    print("\n== selection / inspector ==")

    def select_clip():
        cid = project.all_clips()[0].id
        win.timeline.canvas.selection = {cid}
        win.on_selection_changed([cid])
        settle(300)
        _assert(win.inspector.stack.currentIndex() >= 0, "no inspector page")
    check("selecting a clip switches the inspector", select_clip)

    def tabs():
        for title in ("Layout", "Speed", "Grade", "Effects", "Motion", "Mask"):
            win.inspector.show_tab(title)
            settle(90)
    check("inspector tabs all build", tabs)
    check("inspector screenshot", lambda: shot("04_inspector"))

    def text_clip_inspector():
        text_clip = [c for c in project.all_clips() if c.kind == "text"][0]
        win.timeline.canvas.selection = {text_clip.id}
        win.on_selection_changed([text_clip.id])
        settle(200)
        win.inspector.show_tab("Text")
        settle(250)
    check("text inspector builds", text_clip_inspector)
    check("text inspector screenshot", lambda: shot("05_text_inspector"))

    print("\n== editing operations ==")

    def split():
        win.timeline.canvas.selection = set()
        win.seek(2.0)
        settle(180)
        before = len(project.all_clips())
        win.split_at_playhead()
        settle(200)
        after = len(project.all_clips())
        _assert(after == before + 1, f"{before} -> {after}")
    check("split at playhead", split)

    def undo_redo():
        n = len(project.all_clips())
        win.undo(); settle(120)
        _assert(len(project.all_clips()) == n - 1, "undo did nothing")
        win.redo(); settle(120)
        _assert(len(project.all_clips()) == n, "redo did nothing")
    check("undo / redo", undo_redo)

    def transform_edit():
        clip = [c for c in project.all_clips() if c.kind == "video"][0]
        win.timeline.canvas.selection = {clip.id}
        win.on_selection_changed([clip.id])
        win.inspector.show_tab("Layout")
        settle(150)
        win.ctx.commit("scale", lambda p: setattr(clip.transform, "scale", 1.4))
        win.schedule_preview(); settle(500)
        _assert(abs(clip.transform.scale - 1.4) < 1e-9, "scale not applied")
    check("live transform edit + preview", transform_edit)

    def keyframe():
        clip = [c for c in project.all_clips() if c.kind == "video"][0]
        win.seek(1.0); settle(120)
        win.add_keyframe(); settle(150)
        _assert(clip.has_animation("x") or clip.has_animation("scale"),
                f"no keyframes recorded ({list(clip.animations)})")
    check("add keyframe", keyframe)

    def zoom():
        c = win.timeline.canvas
        z0 = c.px_per_sec
        c.zoom_in(); settle(80)
        _assert(c.px_per_sec > z0, "zoom_in did nothing")
        c.zoom_fit(); settle(80)
    check("timeline zoom", zoom)

    print("\n== dialogs ==")

    def sticker_dialog():
        from vn_editor.ui.dialogs import StickerDialog
        dlg = StickerDialog(win, win.ctx)
        dlg.resize(700, 620)
        dlg.show(); settle(400)
        p = out / "06_stickers.png"
        dlg.grab().save(str(p))
        n = len([k for k in dlg.catalog])
        dlg.close(); settle(120)
        _assert(n >= 30, f"only {n} stickers")
    check("sticker picker (with rendered previews)", sticker_dialog)

    def transitions_dialog():
        from vn_editor.ui.dialogs import TransitionDialog
        clip = [c for c in project.all_clips() if c.kind == "video"][0]
        dlg = TransitionDialog(win, clip, win.ctx)
        dlg.resize(660, 640)
        dlg.show(); settle(350)
        dlg.grab().save(str(out / "07_transitions.png"))
        dlg.close(); settle(100)
    check("transitions dialog", transitions_dialog)

    def sfx_dialog():
        from vn_editor.ui.dialogs import AudioLibraryDialog
        dlg = AudioLibraryDialog(win, win.ctx)
        dlg.resize(680, 620)
        dlg.show(); settle(600)
        dlg.grab().save(str(out / "08_audio_library.png"))
        dlg.close(); settle(100)
    check("sound-effects library dialog", sfx_dialog)

    def export_dialog():
        from vn_editor.ui.dialogs import ExportDialog
        dlg = ExportDialog(win, project)
        dlg.resize(660, 700)
        dlg.show(); settle(400)
        dlg.grab().save(str(out / "09_export.png"))
        dlg.close(); settle(100)
    check("export dialog", export_dialog)

    def other_dialogs():
        from vn_editor.ui import dialogs as D
        for cls, args in ((D.CaptionsDialog, (win, win.ctx)),
                          (D.BeatsDialog, (win, win.ctx)),
                          (D.PresetsDialog, (win, win.ctx)),
                          (D.TextPresetsDialog, (win, win.ctx)),
                          (D.ShortcutsDialog, (win,)),
                          (D.SpeedCurveDialog,
                           (win, [c for c in project.all_clips()
                                  if c.kind == "video"][0], win.ctx))):
            dlg = cls(*args)
            dlg.resize(660, 620)
            dlg.show(); settle(200)
            dlg.grab().save(str(out / f"dialog_{cls.__name__}.png"))
            dlg.close(); settle(60)
    check("captions / beats / presets / text / shortcuts / speed dialogs",
          other_dialogs)

    print("\n== project io ==")

    def save_load():
        from vn_editor.core import project as pio
        path = out / "demo.vnp"
        win.current_path = str(path)
        win.history.mark_saved()
        win.save_project()
        settle(200)
        _assert(path.exists(), "save wrote nothing")
        reloaded = pio.load(str(path))
        _assert(len(reloaded.all_clips()) == len(project.all_clips()),
                "clip count changed after reload")
    check("save / reopen project", save_load)

    def render_frame_now():
        from vn_editor.core import render as render_mod
        from PySide6.QtGui import QImage
        tmp = out / "frame.png"
        ok = render_mod.render_frame(project, 2.5, 270, 480, str(tmp))
        _assert(ok and tmp.exists(), f"frame render failed ({ok})")
        img = QImage(str(tmp))
        _assert(not img.isNull(), "frame is unreadable")
    check("single-frame render (offscreen)", render_frame_now)

    print("\n== result ==")
    failed = [r for r in RESULTS if not r[1]]
    print(f"{len(RESULTS) - len(failed)}/{len(RESULTS)} checks passed")
    for name, _ok, err in failed:
        print(f"  FAILED: {name} — {err}")
    print(f"screenshots in {out}")
    return 1 if failed else 0


def _assert(cond, msg: str) -> None:
    if not cond:
        raise AssertionError(msg)


if __name__ == "__main__":
    sys.exit(main())
